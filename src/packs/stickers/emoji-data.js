// Twemoji dosya adı: ZWJ yoksa FE0F atılır
export function emojiCode(ch) {
  const s = ch.indexOf('‍') < 0 ? ch.replace(/️/g, '') : ch
  const out = []
  for (const c of s) out.push(c.codePointAt(0).toString(16))
  return out.join('-')
}

// [{ ch, name, category, code }]
export function emojiList() {
  const out = []
  for (const cat of EMOJI_CATEGORIES) {
    for (const line of (EMOJI_TEXT[cat.id] || '').split('\n')) {
      const s = line.trim()
      if (!s) continue
      const sp = s.indexOf(' ')
      if (sp < 0) continue
      const ch = s.slice(0, sp)
      out.push({ ch, name: s.slice(sp + 1).trim(), category: cat.id, code: emojiCode(ch) })
    }
  }
  return out
}
