// Ek doku isteyen geçişleri yordamsal dokuyla değiştir
const LUMA_FN = `
float _lh(vec2 p){ return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453); }
float _ln(vec2 p){ vec2 i = floor(p); vec2 f = fract(p); vec2 u = f*f*(3.0-2.0*f);
  return mix(mix(_lh(i), _lh(i+vec2(1,0)), u.x), mix(_lh(i+vec2(0,1)), _lh(i+vec2(1,1)), u.x), u.y); }
vec4 lumaTex(vec2 uv){
  float n = _ln(uv * 4.0) * 0.5 + _ln(uv * 8.0) * 0.25 + _ln(uv * 16.0) * 0.125;
  float g = clamp(n / 0.875 * 0.75 + (1.0 - uv.y) * 0.25, 0.0, 1.0);
  return vec4(vec3(g), 1.0);
}
`
export const GL_PATCHES = {
  LumaWipe: g => g.replace(/uniform sampler2D luma;/, LUMA_FN).replace(/texture\(luma,\s*uv\)/g, 'lumaTex(uv)'),
  DisplacementMap: g => g.replace(/uniform sampler2D displacementMap;/, LUMA_FN).replace(/texture\(displacementMap,\s*uv\)/g, 'lumaTex(uv)'),
}
